  status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' COMMENT '对局状态',
  initial_state JSON NOT NULL COMMENT '创建快照',
  current_state JSON NOT NULL COMMENT '当前完整状态',
  state_version INT NOT NULL DEFAULT 0 COMMENT '行动/放弃时递增',
