  CHECK (task_status IN ('QUEUED','RUNNING','COMPLETED','CANCELLED','FAILED')),
  CHECK (purpose IN ('ANALYSIS','HINT')),
  CHECK (time_limit_ms BETWEEN 100 AND 60000),
  CHECK (node_limit BETWEEN 1000 AND 5000000),
  CHECK (memory_limit_mb BETWEEN 16 AND 128),
  CHECK ((source_type='CUSTOM' AND puzzle_version_id IS NULL AND game_id IS NULL AND game_state_version IS NULL) OR (source_type='PUZZLE_VERSION' AND puzzle_version_id IS NOT NULL AND game_id IS NULL AND game_state_version IS NULL) OR (source_type='GAME' AND puzzle_version_id IS NULL AND game_id IS NOT NULL AND game_state_version IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='持久分析任务及计算快照';

CREATE TABLE solve_result (
  id BIGINT NOT NULL COMMENT '应用生成的正整数ID',
  create_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT 'UTC创建时间',
  update_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT 'UTC更新时间，应用显式维护',
  create_by BIGINT NULL COMMENT '创建者，系统任务可空',
  update_by BIGINT NULL COMMENT '最后更新者',
  deleted TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除0正常1删除',
  task_id BIGINT NOT NULL COMMENT '所属任务唯一',
  proof_status VARCHAR(16) NOT NULL COMMENT 'PROVEN/UNKNOWN',
  winner_side VARCHAR(16) NULL COMMENT '获胜阵营USER/BOT',
  proof_value TINYINT NULL COMMENT 'USER视角+1或-1',
  strategy_status VARCHAR(16) NOT NULL COMMENT 'NONE/PARTIAL/COMPLETE',
  root_node_id BIGINT NULL COMMENT '证明根节点，后置复合外键',
  winning_lines_json JSON NOT NULL COMMENT '最多5条已验证展示路线',
  stats_json JSON NOT NULL COMMENT '最终统计',
  verified_time DATETIME(3) NULL COMMENT '完整证明校验时间',
  PRIMARY KEY (id),
  CONSTRAINT ck_solve_result_deleted CHECK (deleted IN (0,1)),
  UNIQUE KEY uk_result_task (task_id),
  FOREIGN KEY (task_id) REFERENCES solve_task(id),
  CHECK ((proof_status='UNKNOWN' AND winner_side IS NULL AND proof_value IS NULL) OR (proof_status='PROVEN' AND winner_side IS NOT NULL AND proof_value IS NOT NULL AND ((winner_side='USER' AND proof_value=1) OR (winner_side='BOT' AND proof_value=-1)))),
  CHECK (strategy_status IN ('NONE','PARTIAL','COMPLETE')),
  CHECK (strategy_status<>'COMPLETE' OR (proof_status='PROVEN' AND root_node_id IS NOT NULL AND verified_time IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='每任务一个根结论';

