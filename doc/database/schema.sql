CREATE TABLE sys_user (
  id BIGINT NOT NULL COMMENT '应用生成的正整数ID',
  create_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT 'UTC创建时间',
  update_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT 'UTC更新时间，应用显式维护',
  create_by BIGINT NULL COMMENT '创建者，系统任务可空',
  update_by BIGINT NULL COMMENT '最后更新者',
  deleted TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除0正常1删除',
  username VARCHAR(64) NOT NULL COMMENT '规范化用户名，删除后不复用',
  display_name VARCHAR(64) NOT NULL COMMENT '显示名',
  password_hash VARCHAR(255) NOT NULL COMMENT 'BCrypt散列，不对外返回',
  role VARCHAR(16) NOT NULL COMMENT 'GUEST、USER或ADMIN',
  status VARCHAR(16) NOT NULL DEFAULT 'ENABLED' COMMENT '账号状态',
  row_version INT NOT NULL DEFAULT 0 COMMENT '并发版本',
  credential_version INT NOT NULL DEFAULT 0 COMMENT '重置/停用时递增以撤销会话',
  PRIMARY KEY (id),
  CONSTRAINT ck_sys_user_deleted CHECK (deleted IN (0,1)),
  UNIQUE KEY uk_user_username (username),
  CHECK (role IN ('GUEST','USER','ADMIN')),
  CHECK (status IN ('ENABLED','DISABLED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='本系统账号；固定单角色';

