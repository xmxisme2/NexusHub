CREATE TABLE puzzle (
  id BIGINT NOT NULL COMMENT '应用生成的正整数ID',
  create_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT 'UTC创建时间',
